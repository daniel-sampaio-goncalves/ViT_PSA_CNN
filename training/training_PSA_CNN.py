def load_patterns_codebook(path:str|Path="./data/Pattern/All_patterns.csv"):
    """
    Loads the groundtruth CSV file generated from the `syntheticpattern` package,
    extracts the patch pattern and converts it into a single tensor of shape [B,N,P,P]
    
    Args:
        path (str|Path): dir of the codebook csv file generated by the `syntheticpattern` package
    Returns:
        torch.Tensor ([B,N,P,P]):
            - Tensor containing the codebooks patch patterns
    """
    all_patterns_df=load_pattern_csv(path)
    return torch.stack( all_patterns_df["pattern"].tolist())

def scale_and_binarize_patches_n(cnn_patches:torch.Tensor, threshold_ratio:float=0.7, binary_error_ratio:float=0.37) -> tuple[torch.Tensor, torch.Tensor]:
    """
    Classify each predicted patch as confidently-binary. It only returns the raw
    binarized patches and a per-patch confidence flag.

    Note:
    -----
        There is an unintended behavior from an earlier version of the function that wasn't caught before
        training the current best performing model. For `the threshold_ratio`, the mask 
        `active_mask.any(dim=(-1, -2), keepdim=True)` has the values  of each patch that passed (true) 
        and failed (false) the threshold_ratio. Since, `.any()` was used it will always return `True` 
        as every patch has at least one max value. Hence the `threshold_ratio` filtering 
        doesn't apply at all. As the model was trained successfully with this "bug", this behaviour 
        wasn't fixed intenionally and was left for reference.

    Args:
        cnn_patches (torch.Tensor): Decoder output patches to classify of shape [B, M, P, P]
        threshold_ratio (float): float that multiplies the max intenisty of a given patche's 
            value with this threshold. Any intensity below this threshold gets flagged to be
            masked. Due to the bug above, this currently has no effect on the
            returned `confident_mask` (see Note).
        binary_error_ratio (float): Maximum allowed average distance from 0 or 1 that patch intensities 
                can diverge (how far away can the average pixel be from 0s or 1s in a given patch).

    Returns:
        tuple[torch.Tensor, torch.Tensor]:
            binary [B,M,P,P]:
                - Every patch binarized via a per-patch scaling, if a value is lower than 0.5 it becomes 0 else 1.
            
            confident_mask [B,M,1,1]:
                - True wherever a patch's `binary_error_ratio` check passed 
                (see Note `threshold_ratio` component not being applied correctly).
    
    """
    patch_max = cnn_patches.amax(dim=(-1, -2), keepdim=True)
    patch_min = cnn_patches.amin(dim=(-1, -2), keepdim=True)

    active_mask = cnn_patches >= patch_max * threshold_ratio
    binary_error = torch.minimum(cnn_patches, 1 - cnn_patches).mean(dim=(-1, -2), keepdim=True)
    binary_mask = binary_error <= binary_error_ratio
    confident_mask = (binary_mask & active_mask.any(dim=(-1, -2), keepdim=True)).view(
        cnn_patches.shape[0], cnn_patches.shape[1]
    )

    scaled = (cnn_patches - patch_min) / (patch_max - patch_min + 1e-8)
    binary = (scaled >= 0.5).float()
    return binary, confident_mask


def match_and_fetch_intensities_alldiv_n(
    cnn_patch:torch.Tensor, 
    valid_patterns:torch.Tensor, 
    initial_tensor:torch.Tensor,
    threshold_ratio:float=0.7, 
    binary_error_ratio:float=0.37
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:

    """ For each `cnn_patch` patch match it against a pattern codebook,
    and fetch the true intensity for that batch, and return
    the true intensity patches that passed thresholding in addition to 
    weights and masks regarding matchings, see Returns below

    Note:
    -----
    see :func:`scale_and_binarize_patches_n`'s Note regarding
    `threshold_ratio` being not used due to a preserved bug.
    Also requires P*P <= 64, since each flattened binary pattern is
    packed into a single int64 via bit-shifting (`1 << arange(P*P)`)

    Args:
        cnn_patch (torch.Tensor [B,M,P,P]): Decoder output patches to clean.
        
        valid_patterns (troch.Tensor [N,P,P]): Codebook of known-valid binary patterns

        initial_tensor (torch.Tensor [B,N,P,P]): Original true-intensity input tensor the decoder (soft) permuted.

        threshold_ratio (float): Forwarded to :func:`scale_and_binarize_patches_n`.

        binary_error_ratio (float): Forwarded to :func:`scale_and_binarize_patches_n`.
        
    Returns:
        tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
            target [B, M, P, P]: 
              - True intensity patches for every exactly-matched and filtered binary patch
                Patches are all-zero if they failed confidence thresholding or matched
                nothing in the codebook.
            
            weight [B, M], values {0, 1}: 
              - where 1 is a patch that was confidently binary AND matched the codebook
                exactly; 0 otherwise.

            confident_mask [B,M], dtype bool: 
              - Passed through directly from :func:`scale_and_binarize_patches_n`, True wherever 
                a patch's `binary_error_ratio` check passed (see Note `threshold_ratio` component not being applied correctly).
            
            raw_binary [B, M, P, P], values in {0, 1}:
                - The *unfiltered* binarized patches from :func:`scale_and_binarize_patches_n`,
                before `confident_mask` is applied (includes patches
                that failed filter thresholding).

            category [B,M]: 
              - Codebook index of the matched pattern for patches that matched, 
                -1 for every patch that didn't survive cleaning.
    """
    device = cnn_patch.device
    _, _, P, _ = cnn_patch.shape

    # Get the raw binarized patches, and the mask for patches that passed/failed thresholding 
    raw_binary, confident_mask = scale_and_binarize_patches_n(cnn_patch, threshold_ratio, binary_error_ratio)

    # Next unconfident patches get their failed pattern zeroed out before hashing and matching.
    binary = raw_binary * confident_mask[..., None, None].float()
    patches_flat = binary.to(torch.long).flatten(start_dim=2)                              
    valid_flat = valid_patterns.to(torch.long).unsqueeze(0).flatten(start_dim=2) # unsqueeze for [N,P,P]->[B,N,P*P]

    # hashing
    weights = 1 << torch.arange(P * P, device=device, dtype=torch.int64)
    patch_keys = (patches_flat * weights).sum(-1)     # (B,M)
    valid_keys = (valid_flat * weights).sum(-1)        # (1,N)
    # look for exact matches:
    exact = patch_keys.unsqueeze(-1) == valid_keys.unsqueeze(1)   # [B,M,N]
    exact_mask = exact.any(-1)                                    # [B,M], get the surviving patches (true) that matched the codebook
    exact_idx = exact.float().argmax(-1)                          # Get the exact ids from the codebook for each M patch that matched, argmax works here since only 1 patch exists in the codebook

    # Category here is used for diversity loss downstream.
    # matched patches get their codebook index, and every patch 
    # that didn't survive cleaning assigned to index (-1),
    # to treat them as duplicates of each other rather than 
    # excluded from the check.
    category = torch.where(exact_mask, exact_idx, torch.full_like(exact_idx, -1))

    # get the values of the initial tensor
    target = torch.gather(initial_tensor, dim=1, index=exact_idx[..., None, None].expand(-1, -1, P, P))
    # get rid of the patches that had failed matching, keep the real 0 index patch
    target = target * exact_mask[..., None, None]
    weight = exact_mask.float()

    return target, weight, confident_mask, raw_binary, category

def patch_hash_diversity_loss_all_diversity_n(
          cnn_patches:torch.Tensor, 
          valid_patterns:torch.Tensor, 
          initial_tensor:torch.Tensor,
          threshold_ratio:float=0.7, 
          binary_error_ratio:float=0.37,
          eps:float=1e-8) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """
    Penalizes reuse of the same *cleaned* pattern across multiple patches
    within a sample. "Cleaned" patches mean that they exactly match a given
    codebook pattern in `valid_patterns`. Every patch that
    doesn't survive cleaning is grouped into one shared "blank" patch, meaning
    so repeated blanks count also as duplicates too.

    Combines two training losses in one pass: 
     - a reconstruction loss (`aux_loss`), 
       calculating MSE against matched true intensities. Meaning how far away 
       is the `cnn_patches` given patch from the cleaned true value matching 
       patch present in `initial_tensor`.
     - a diversity penalty (`div_loss`) which is a cosine similarity between 
       patches sharing the same category (index of the patternbook/initial_tensor or blanks, 
       see :func:`match_and_fetch_intensities_alldiv_n` returns),
       consequently discouraging the decoder from placing duplicate patterns.
    
    Note:
    -----
     While `div_loss` here discourages two duplicates from being exactly the same, 
     `aux_loss` pushes them to become similar (with the goal of obtaining the 
     `initial_tensor` matching pattern intensity), therefore
     these losses may be countering each other. However aux doesn't affect blancs, 
     while they penalize div. Additionnally, if the model shifts from a duplication 
     into a new (unique) pattern from a different `initial_tensor` idx (category) it  
     will benefit the diversity loss.

    Args:
        cnn_patches (torch.Tensor [B,M,P,P]): Decoder output croped patches.
        valid_patterns (torch.Tensor [1,N,P,P]): Codebook of known-valid binary patterns
        initial_tensor (troch.Tensor [B,N,P,P]): Original true intensity model input tensor before permutation
        threshold_ratio (float): Forwarded to :func:`scale_and_binarize_patches_n`, see that
            function's Note on this having no effect due to a preserved bug).
        binary_error_ratio (float): Forwarded to :func:`match_and_fetch_intensities_alldiv_n`.
        eps (float): Numerical stability epsilon passed to `F.normalize` when
            computing cosine similarity between patches to avoid 0 divisions.

    Returns:
        tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
            - div_loss (torch.Tensor Scalar): Mean of the average
              pairwise cosine similarity among same category patch pairs
              per sample.
            - aux_loss (torch.Tensor, Scalar): MSE between `cnn_patches` and
              their matched true intensity targets
            - weight (torch.Tesnor [B,M] values in {0, 1}): tensor where 1 is a patch that 
              was confidently binary AND matched the codebook exactly, 0 otherwise.
              See :func:`match_and_fetch_intensities_alldiv_n`
    """
    valid_patterns = valid_patterns.to(device=cnn_patches.device, dtype=cnn_patches.dtype)
    initial_tensor = initial_tensor.to(device=cnn_patches.device, dtype=cnn_patches.dtype)

    # Get the binary cleaned patches and weights
    # Catagory here is the index of the codebook that a given patch in cnn_patches matched
    # or blanks (including mismatched patches) 
    target, weight, _, _, category = match_and_fetch_intensities_alldiv_n(
        cnn_patch=cnn_patches, 
        valid_patterns=valid_patterns, 
        initial_tensor=initial_tensor,
        threshold_ratio=threshold_ratio, 
        binary_error_ratio=binary_error_ratio)
    
    # Calculate MSE loss between cnn_patches and cleaned patches
    per_patch = F.mse_loss(cnn_patches, target, reduction='none').mean(dim=(-1, -2))   # (B,M)
    # add the weights, so unmatched/wrong patches don't penalize the model, we're just after the error between valid patterns
    aux_loss = (per_patch * weight).sum() / weight.sum().clamp(min=1)

    _, M, _, _ = cnn_patches.shape

    # Two patches count as duplicates when they share a category value. 
    # same matched codebook index, or if both are blank. 
    # Comparing category [B,M] between [B,M,1] and [B,1,M] 
    # results int [b, i, j] where True is exactly when patch i and patch j (within sample b) 
    # have the same value either both matched the same codebook entry, 
    # or both are blank (-1 == -1).
    same_category = category.unsqueeze(2) == category.unsqueeze(1)   # [B,M,1]==[B,1,M] -> [B,M,M]

    # We invert an identity matrix to become False on the diagonal to delete 
    # same patch comparisions which would other wise count as duplicates and 
    # increase the diversity loss later.
    pair_mask = same_category & ~torch.eye(M, dtype=torch.bool, device=cnn_patches.device)

    # Computing a patch pairwise similarity matrix 
    # L2 normalize and calculate the cosine similarity
    shape = F.normalize(cnn_patches.clamp(min=0).flatten(2), dim=-1, eps=eps)
    sim = torch.matmul(shape, shape.transpose(-2, -1)).clamp(min=0)                # [B,M,M]
    # Let's zero out similarities for non-duplicate patches
    penalty = (sim * pair_mask.float()).sum(dim=(-1, -2))
    # Count how many duplications we got
    denom = pair_mask.float().sum(dim=(-1, -2)).clamp(min=1)
    # divide penalty with amount of pairs to get the diversity loss
    div_loss = (penalty / denom).mean()

    return div_loss, aux_loss, weight


##### Annealing ######
def window_jitter_anneal(epoch:int, 
                         size_start:int=64, 
                         size_end:int=12, 
                         shrink_epochs:int=26,
                         jitter_max:int=4, 
                         jitter_span:int=5
                         ) -> tuple[torch.Tensor,torch.Tensor]:
    
    """
    Calculate a window size and ajitter amount as a function of epochs.
    The function will calculate annealing values for a decreased window size,
    and window position jitter (around the center)

    Args:
        epoch (int): Current training epoch.
        size_start (int): Window size at epoch 0
        size_end (int): Window size expected at the `shrink_epoch`
        shrink_epochs (int): Number of epochs over which window_size ramps from
            `size_start` to `size_end`.
        jitter_max (int): value at which jitter stops increasing.
        jitter_span (int):  Controls the scale of the jitter ramp-up. Larger values
            make jitter increase more slowly; smaller values make it increase
            more quickly. formula: ((10/`shrink_epochs`)*`epoch`+1)/ `jitter_span`)

    Returns:
        tuple[torch.Tensor, torch.Tensor]:
            - window_size (0d, int64 tensor)
            - jitter (0d, int64 tensor)
    """
    # derive the per-epoch step from the desired start/end/duration
    size_step = (size_start - size_end) / shrink_epochs


    if epoch < shrink_epochs:
        window_size = round(size_start - size_step * epoch)

    else:
        window_size = size_end
        
    # calculate a linear function of epochs, divide by 10 for a slower growth
    # and add a jitter growth each jitter span
    perten=((10/shrink_epochs)*epoch+1)
    jitter = math.floor(min( perten / jitter_span, jitter_max))
    
    return torch.tensor(window_size, device='cuda'), torch.tensor(jitter, device='cuda')

##### Metric fn ########
def accuracy_fn_binary(y_true:torch.Tensor, y_preds:torch.Tensor)-> torch.Tensor:
    """
    Compute binary classification accuracy as a percentage.

    Args:
        y_true (torch.Tensor): Ground-truth binary labels between {0, 1}
        _y_preds (torch.Tensor): Predicted probabilities scores between {0, 1} (e.g. after sigmoid)

    Returns:
        float: Accuracy as a percentage as a tensor
    """
    y_preds = (y_preds >= 0.5).int()
    return (y_preds == y_true).float().mean() * 100


