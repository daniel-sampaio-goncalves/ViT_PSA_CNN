def evaluation_autocast(model: nn.Module, 
                        test_data_loader: torch.utils.data.DataLoader[dict[str,torch.Tensor]],
                        loss_fn:Callable[[torch.Tensor, torch.Tensor], torch.Tensor], 
                        accuracy_fn:Callable[[torch.Tensor, torch.Tensor], torch.Tensor]=accuracy_fn_binary, 
                        object_index:list[str]=["image","label"],
                        grid_size:int=64,
                        window_size:torch.Tensor|int=18,
                        jitter:torch.Tensor|int=0,
                        valid_patterns_tensor:torch.Tensor=load_patterns_codebook(),
                        aux_w:torch.Tensor|float|int=1,
                        div_w:torch.Tensor|float|int=1,
                        BCE_weight:torch.Tensor|float|int=0.8) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
    """
    Evaluate the model on a data loader under bf16 autocast, returning mean losses and accuracy.

    Args:
        model (nn.Module): model, must already be on CUDA.
        test_data_loader (torch.utils.data.DataLoader[dict[str,torch.Tensor]]): A pytorch DataLoader with batches as dictionaries with the keys mapping to tensors given in `object_index`.
        loss_fn (Callable): Classification loss function called as `loss_fn(logits, label)`.
        accuracy_fn (Callable): accuracy metric function with probabilities as arguments.
        object_index (list[str]): Keys used to access the tensors in each batch returned by `test_data_loader`.
        grid_size (int): Patch-grid side length forwarded to the model.
        window_size (torch.Tensor|int): CNN window size forwarded to the model (`cnn_window_size`). 
            *Note: if using an annealed value with `torch.compile`, prefer a dynamic representation (e.g. Tensor) instead of a Python `int` to avoid potential recompilations.*
        jitter(torch.Tensor|int): CNN window jitter forwarded to the model (`cnn_jitter`). *Note: same note as `window_size`
        valid_patterns_tensor (torch.Tensor): A Codebook of shape [N,P,P] of valid patch patterns.
        aux_w (torch.Tensor|float|int): Weight on the auxiliary loss.
        div_w (torch.Tensor|float|int): Weight on the diversity loss.
        BCE_weight (float): Weight on the classification (BCE) loss.

    Returns:
        tuple (total_loss[torch.Tensor], accuracy[torch.Tensor], BCE_loss[torch.Tensor], diversity_loss[torch.Tensor], aux_loss[torch.Tensor]):
            each averaged over batches.
    """
    
    if torch.cuda.is_available():
         device = 'cuda'  
    else:
         raise RuntimeError("CUDA is not available. This code uses CUDA-specific optimizations and cannot run on CPU.")

    model.eval()
    
    test_loss = torch.zeros((), device=device)
    test_acc = torch.zeros((), device=device)
    test_BCE_Loss = torch.zeros((), device=device)
    test_div_loss = torch.zeros((), device=device)
    test_aux_loss = torch.zeros((), device=device)
    
    label:torch.Tensor
    
    n_samples=0


    with torch.inference_mode(), torch.autocast(device_type='cuda', dtype=torch.bfloat16):
        for batch, loaded_data in enumerate(test_data_loader):

            X,label  = loaded_data[object_index[0]], loaded_data[object_index[1]]
            
            X=X.to(device, non_blocking=True, memory_format=torch.channels_last)

            label=label.to(device, dtype=torch.float32, non_blocking=True)
            test_label, _, cnn_patch=model(
                X,
                grid_size=grid_size,
                cnn_window_size=window_size,
                cnn_jitter=jitter
                )


            # losses
            
            div_loss, aux_loss, _=patch_hash_diversity_loss_all_diversity_n(cnn_patches=cnn_patch, valid_patterns=valid_patterns_tensor,initial_tensor=X)
            BCE_Loss=loss_fn(test_label, label)

  
            
            loss =  (BCE_weight*BCE_Loss) + (div_w*div_loss) + (aux_w*aux_loss)
        
            # adjust for the last batch if smaller size: 
            n = label.shape[0]  # per-batch size, read inside the loop so it is that batch's own size
            n_samples += n

            test_loss+=loss * n
            test_BCE_Loss+=BCE_Loss * n
            y_predictions:torch.Tensor=(torch.sigmoid(test_label)).to(dtype=torch.float32)
            test_acc+=accuracy_fn(label, y_predictions) *n
            test_div_loss += div_loss *n
            test_aux_loss += aux_loss *n


        test_loss/=n_samples
        test_acc/=n_samples
        test_BCE_Loss/=n_samples
        test_div_loss/=n_samples
        test_aux_loss/=n_samples

    return test_loss,test_acc,test_BCE_Loss, test_div_loss,test_aux_loss


def train_autocast(model:nn.Module, 
                   train_data_loader: torch.utils.data.DataLoader[dict[str,torch.Tensor]],
                   optimizer:torch.optim.Optimizer,
                   loss_fn:Callable[[torch.Tensor, torch.Tensor],torch.Tensor], 
                   accuracy_fn:Callable[[torch.Tensor, torch.Tensor],torch.Tensor]=accuracy_fn_binary, 
                   scheduler: torch.optim.lr_scheduler.LRScheduler|None=None, 
                   grad_clip:bool=False, 
                   max_grad_norm:float = 1.0, 
                   object_index:list[str]=["image","label"],
                   grid_size:int=64,
                   window_size:torch.Tensor|int=18,
                   jitter:torch.Tensor|int=0,
                   valid_patterns_tensor:torch.Tensor=load_patterns_codebook(),
                   aux_w:torch.Tensor|int|float=1,
                   div_w:torch.Tensor|int|float=1,
                   BCE_weight: torch.Tensor|int|float=0.8) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
    """
    Runs one training epoch under bf16 autocast and return a sample weighted mean losses and accuracy.
    Batches whose gradient norm is non-finite are skipped (no optimizer or scheduler step) and
    excluded from the returned averages.

    Args:
        model (nn.Module): model, must already be on CUDA.
        train_data_loader (torch.utils.data.DataLoader[dict[str,torch.Tensor]]): A pytorch DataLoader with batches as dictionaries with the keys mapping to tensors given in `object_index`.
        optimizer (optim.Optimizer): pytorch optimizer stepped once per batch with a finite gradient norm.
        loss_fn (Callable): classification loss `loss_fn(logits, label)` (e.g. BCE with logits).
        accuracy_fn (Callable):  accuracy metric function with probabilities as arguments.
        scheduler (lr_scheduler.LRScheduler) | None: Optionally, a per batch scheduler, defaults to None.
        grad_clip (bool): Defaults to False. If True, clips the global gradient norm to `max_grad_norm`.
        max_grad_norm (float): Clipping threshold, used only when `grad_clip` is True.
        object_index (list[str]): Keys used to access the tensors in each batch returned by `train_data_loader`.
        grid_size (int): Patch grid side length forwarded to the model.
        window_size (torch.Tensor|int): The CNN window size used on 75% of batches ( automatically converted to a 0-d int64 CUDA tensor).
        jitter (torch.Tensor|int): CNN window jitter forwarded to the model (`cnn_jitter`).
            *Note: if using an annealed value with `torch.compile`, prefer a dynamic representation (e.g. Tensor) instead of a Python `int` to avoid potential recompilations.*
        valid_patterns_tensor (torch.Tensor): A Codebook of shape [N,P,P] of valid binary patch patterns.
        aux_w (torch.Tensor|int|float): Weight on the auxiliary loss term.
        div_w (torch.Tensor|int|float): Weight on the diversity loss term.
        BCE_weight (torch.Tensor|int|float): Weight on the classification (BCE) loss term.

    Returns:
        tuple(total_loss[torch.Tensor], accuracy[torch.Tensor], BCE_loss[torch.Tensor], diversity_loss[torch.Tensor], aux_loss[torch.Tensor]):
            each averaged over batches. If every batch was skipped, all five are zero tensors and prints a message.

    Raises:
        RuntimeError: If CUDA is not available.
    """

    if torch.cuda.is_available():
        device = 'cuda'
         
        # Changing window size to a 0-d int64 tensor to avoid recompilation if using torch.compile, as otherwise we'd switch between torch.rand vaules and a plain int 
        window_size=torch.as_tensor(window_size, device=device, dtype=torch.int64)
    else:
         raise RuntimeError("CUDA is not available. This code uses CUDA-specific optimizations and cannot run on CPU.")

    # create training metrics in gpu directly
    train_loss = torch.zeros((), device=device)
    train_acc = torch.zeros((), device=device)
    train_BCE_Loss = torch.zeros((), device=device)
    train_div_loss =torch.zeros((), device=device)
    train_aux_loss = torch.zeros((), device=device)
    # used to devide total samples at the end of each epoch for the sample weighted average. Counts only samples from batches that were actually applied.
    n_samples=0

    model.train()
    for batch, loaded_data in enumerate(train_data_loader):
        
        # To keep track of skiped samples later
        skip_count:bool=False

        X, label = loaded_data[object_index[0]], loaded_data[object_index[1]]
        X=X.to(device, non_blocking=True, memory_format=torch.channels_last) # didn't test: memory_format=torch.channels_last for images going through cnns; tested and works: non_blocking=True allows the GPU to start working on one batch while the next batch is still being loaded on CPU.
        label=label.to(device, dtype=torch.float32, non_blocking=True)
        
        # we use torch.rand to keep the torch cpu randomness seed instead of python's, and use device == cpu for the if to avoid an additional gpu/cpu sync overhead 
        if torch.rand((), device="cpu") < 0.25:
            applied_window_size = torch.randint(18, 23, (), device=device)
        else:
            applied_window_size = window_size

        with torch.autocast(device_type='cuda', dtype=torch.bfloat16): # trains in bflat16 lower memory and faster less precision though - no gradscaling necessary compared
            # forward
            pred_label,_, cnn_patch=model(X, 
                                    grid_size=grid_size,
                                    cnn_window_size=applied_window_size,
                                    cnn_jitter=jitter
                                    )
            
            # losses
            div_loss, aux_loss, _=patch_hash_diversity_loss_all_diversity_n(cnn_patches=cnn_patch, valid_patterns=valid_patterns_tensor,initial_tensor=X)

            BCE_Loss= loss_fn(pred_label, label)

            # loss formula
            loss =  (BCE_weight*BCE_Loss) + (div_w*div_loss) + (aux_w*aux_loss)

        
        # backward
        loss.backward()

        # Compute grad norm, even if grad_clip is off to detect non finite gradients 
        # regardless of whether clipping itself was enabled.
        grad_norm = torch.nn.utils.clip_grad_norm_(
            model.parameters(),
            max_grad_norm if grad_clip else float('inf')
        )
        
        # track samples
        n = label.shape[0]
        
        # Skip the optimizer step if the computed gradient norm is NaN or infinite. 
        # Note: grad_norm is a CUDA scalar, so using if + torch.isfinite(grad_norm) here slows down training. 
        # This check is currently needed because the model produces NaNs.

        if not torch.isfinite(grad_norm):
            print(f"Skipping step: non-finite grad norm {grad_norm.item()}")
            print(f"###")
            print(f"###")
            skip_count=True
            optimizer.zero_grad(set_to_none=True)
        
        else:
            optimizer.step()
            optimizer.zero_grad(set_to_none=True)

            if scheduler:
                scheduler.step()

        if skip_count is False:
            # keep track of samples
            n_samples += n

            # track losses
            # Accumulate the metrics without retaining autograd graphs, and avoid memory growth from previous its.
            with torch.no_grad():
                
                train_loss+=loss.detach() *n # technically nograd already solves this, but a for insurance sake, there's no harm in detaching so the losses additionally from any computation graphs.
                train_BCE_Loss+=BCE_Loss.detach() *n
                train_div_loss += div_loss.detach() *n
                train_aux_loss += aux_loss.detach() *n
                predicted_labels=(torch.sigmoid(pred_label)).to(dtype=torch.float32)
                train_acc+=accuracy_fn(label, predicted_labels).detach() *n

                

        if batch == 0:
            print(f"Batch: {batch}/{len(train_data_loader)}")
        if (batch + 1) % 100 == 0:
            print(f"Batch: {batch+1}/{len(train_data_loader)}")
        elif (batch+1) == len(train_data_loader):
            print(f'Batch: {batch+1}/{len(train_data_loader)}')
    

    #Avoid division by 0 if every batch is infinite
    if n_samples!=0:
        train_loss /=n_samples
        train_BCE_Loss/=n_samples
        train_acc /=n_samples
        train_div_loss/=n_samples
        train_aux_loss/=n_samples
    else:
        print("Skipped everything loss are 0 as a result")

    return train_loss,train_acc, train_BCE_Loss, train_div_loss,train_aux_loss

